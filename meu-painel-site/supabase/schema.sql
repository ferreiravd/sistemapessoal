create table if not exists public.agenda_events (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  title text not null,
  description text default '',
  event_date date not null,
  event_time time,
  created_at timestamptz not null default now()
);
create table if not exists public.brainstorm_notes (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  title text default '',
  content text not null,
  color text not null default 'gold' check (color in ('gold','green','cream')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create table if not exists public.work_settings (
  id integer primary key default 1 check (id = 1),
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  daily_minutes integer not null default 528 check (daily_minutes between 0 and 1440),
  updated_at timestamptz not null default now(),
  unique(user_id)
);
create table if not exists public.work_entries (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  work_date date not null,
  start_time time not null,
  end_time time not null,
  break_minutes integer not null default 0 check (break_minutes >= 0),
  observation text default '',
  created_at timestamptz not null default now(),
  unique(user_id, work_date)
);
alter table public.agenda_events enable row level security;
alter table public.brainstorm_notes enable row level security;
alter table public.work_settings enable row level security;
alter table public.work_entries enable row level security;

drop policy if exists "private agenda events" on public.agenda_events;
create policy "private agenda events" on public.agenda_events for all to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);
drop policy if exists "private brainstorm notes" on public.brainstorm_notes;
create policy "private brainstorm notes" on public.brainstorm_notes for all to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);
drop policy if exists "private work settings" on public.work_settings;
create policy "private work settings" on public.work_settings for all to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);
drop policy if exists "private work entries" on public.work_entries;
create policy "private work entries" on public.work_entries for all to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);

-- Atualiza automaticamente a data de edição das anotações.
create or replace function public.touch_updated_at()
returns trigger language plpgsql as $$
begin new.updated_at = now(); return new; end; $$;
drop trigger if exists brainstorm_updated_at on public.brainstorm_notes;
create trigger brainstorm_updated_at before update on public.brainstorm_notes
for each row execute function public.touch_updated_at();